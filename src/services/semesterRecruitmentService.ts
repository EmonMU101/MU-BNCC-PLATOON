import { doc, getDoc, setDoc, onSnapshot } from 'firebase/firestore';
import { db } from '../lib/firebase';

export interface RecruitmentTimelineSheet {
  id: string; // e.g. "fall-2026"
  semester: string; // e.g. "Fall 2026"
  semesterBn?: string;
  sheetTitle: string; // e.g. "MU BNCC Cadet Recruitment Roster - Fall 2026"
  sheetUrl: string; // Direct Google Sheets URL
  createdAt: string;
  applicantCount: number;
  lastSyncedAt?: string;
  autoGenerated: boolean;
}

export interface SemesterSettings {
  currentSemester: string; // e.g. "Fall 2026", "Spring 2026"
  currentSemesterBn?: string; // e.g. "ফল ২০২৬", "স্প্রিং ২০২৬"
  applicationDeadline: string; // ISO date string e.g. "2026-11-30T23:59:59.000Z"
  semesterEndDate: string; // ISO date string e.g. "2026-12-31T23:59:59.000Z"
  googleSheetUrl: string; // Auto-generated or custom SheetDB/Google Sheet endpoint
  syncEnabled: boolean;
  lastSyncAt?: string;
  timelineSheets?: RecruitmentTimelineSheet[];
}

export const getAutoGeneratedSheetUrl = (semesterName: string): string => {
  const clean = semesterName.trim() || 'New Recruitment Cycle';
  const title = `MU BNCC Cadet Recruitment - ${clean}`;
  return `https://docs.google.com/spreadsheets/create?title=${encodeURIComponent(title)}`;
};

export const ensureTimelineSheetExists = (
  semesterName: string,
  currentSheets: RecruitmentTimelineSheet[] = []
): { sheet: RecruitmentTimelineSheet; updatedSheets: RecruitmentTimelineSheet[] } => {
  const clean = semesterName.trim() || 'Fall 2026';
  const id = clean.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  const existing = currentSheets.find(
    (s) => s.id === id || s.semester.toLowerCase() === clean.toLowerCase()
  );

  if (existing) {
    return { sheet: existing, updatedSheets: currentSheets };
  }

  const newSheet: RecruitmentTimelineSheet = {
    id,
    semester: clean,
    sheetTitle: `MU BNCC Cadet Recruitment Roster - ${clean}`,
    sheetUrl: getAutoGeneratedSheetUrl(clean),
    createdAt: new Date().toISOString(),
    applicantCount: 0,
    lastSyncedAt: new Date().toISOString(),
    autoGenerated: true,
  };

  return {
    sheet: newSheet,
    updatedSheets: [newSheet, ...currentSheets],
  };
};

