export const getLocalSemesterSettings = (): SemesterSettings => {
  try {
    const raw = localStorage.getItem(SETTINGS_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      const combined = { ...DEFAULT_SEMESTER_SETTINGS, ...parsed };
      if (!combined.googleSheetUrl || combined.googleSheetUrl.includes('sheetdb_demo') || combined.googleSheetUrl.includes('demo')) {
        combined.googleSheetUrl = getAutoGeneratedSheetUrl(combined.currentSemester);
      }
      return combined;
    }
  } catch (err) {
    console.warn('Failed to parse local semester settings:', err);
  }
  return DEFAULT_SEMESTER_SETTINGS;
};

export const setLocalSemesterSettings = (settings: SemesterSettings) => {
  try {
    localStorage.setItem(SETTINGS_KEY, JSON.stringify(settings));
    window.dispatchEvent(new CustomEvent('semester-settings-changed', { detail: settings }));
  } catch (err) {
    console.warn('Failed to save local semester settings:', err);
  }
};

/**
 * Fetch current semester settings from Firestore with local fallback
 */
export const getSemesterSettings = async (): Promise<SemesterSettings> => {
  try {
    const docRef = doc(db, 'system_settings', 'recruitment_semester');
    const snap = await getDoc(docRef);
    if (snap.exists()) {
      const data = snap.data() as Partial<SemesterSettings>;
      const combined = { ...DEFAULT_SEMESTER_SETTINGS, ...data };
      if (!combined.googleSheetUrl || combined.googleSheetUrl.includes('sheetdb_demo') || combined.googleSheetUrl.includes('demo')) {
        combined.googleSheetUrl = getAutoGeneratedSheetUrl(combined.currentSemester);
      }
      setLocalSemesterSettings(combined);
      return combined;
    }
  } catch (err) {
    console.warn('Firestore getSemesterSettings failed, using local cache:', err);
  }
  return getLocalSemesterSettings();
};

/**
 * Save updated semester & deadline settings to Firestore and local storage,
 * automatically creating a dedicated recruitment sheet for the timeline.
 */
export const saveSemesterSettings = async (
  updates: Partial<SemesterSettings>
): Promise<SemesterSettings> => {
  const current = getLocalSemesterSettings();
  const targetSemester = updates.currentSemester?.trim() || current.currentSemester;
  
  // Auto-generate / ensure timeline sheet exists for this recruitment cycle
  const { sheet, updatedSheets } = ensureTimelineSheetExists(
    targetSemester,
    updates.timelineSheets || current.timelineSheets || DEFAULT_SEMESTER_SETTINGS.timelineSheets
  );

  const autoUrl = updates.googleSheetUrl?.trim() || sheet.sheetUrl || getAutoGeneratedSheetUrl(targetSemester);

  const next: SemesterSettings = {
    ...current,
    ...updates,
    currentSemester: targetSemester,
    googleSheetUrl: autoUrl,
    timelineSheets: updatedSheets,
    lastSyncAt: new Date().toISOString(),
  };

  setLocalSemesterSettings(next);

  try {
    const docRef = doc(db, 'system_settings', 'recruitment_semester');
    await setDoc(docRef, next, { merge: true });
  } catch (err) {
    console.warn('Firestore setDoc failed for semester settings:', err);
  }

  return next;
};

/**
 * Listen for real-time changes to the semester & deadline settings
 */
export const subscribeSemesterSettings = (
  callback: (settings: SemesterSettings) => void
): (() => void) => {
  callback(getLocalSemesterSettings());

  const handleCustomEvent = (e: Event) => {
    const detail = (e as CustomEvent<SemesterSettings>).detail;
    if (detail) callback(detail);
  };
  window.addEventListener('semester-settings-changed', handleCustomEvent);

  let unsubFirestore = () => {};
  try {
    const docRef = doc(db, 'system_settings', 'recruitment_semester');
    unsubFirestore = onSnapshot(
      docRef,
      (snap) => {
        if (snap.exists()) {
          const data = snap.data() as Partial<SemesterSettings>;
          const combined = { ...DEFAULT_SEMESTER_SETTINGS, ...data };
          setLocalSemesterSettings(combined);
          callback(combined);
        }
      },
      (err) => {
        console.warn('Firestore subscription error for semester settings:', err);
      }
    );
  } catch (err) {
    console.warn('Could not attach Firestore onSnapshot for semester settings:', err);
  }

  return () => {
    window.removeEventListener('semester-settings-changed', handleCustomEvent);
    unsubFirestore();
  };
};

/**
 * Calculate dynamic countdown to application deadline or semester end
 */
export interface CountdownResult {
  days: number;
  hours: number;
  minutes: number;
  seconds: number;
  isExpired: boolean;
  totalMs: number;
}

export const calculateCountdown = (targetIsoDate: string): CountdownResult => {
  const target = new Date(targetIsoDate).getTime();
  const now = Date.now();
  const diff = target - now;

  if (diff <= 0 || isNaN(diff)) {
    return {
      days: 0,
      hours: 0,
      minutes: 0,
      seconds: 0,
      isExpired: true,
      totalMs: 0,
    };
  }

  const days = Math.floor(diff / (1000 * 60 * 60 * 24));
  const hours = Math.floor((diff % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
  const minutes = Math.floor((diff % (1000 * 60 * 60)) / (1000 * 60));
  const seconds = Math.floor((diff % (1000 * 60)) / 1000);

  return {
    days,
    hours,
    minutes,
    seconds,
    isExpired: false,
    totalMs: diff,
  };
};
